<?php

function is_money_value($value) {
  return preg_match('/^\d+(?:\.\d{1,2})?$/D', trim((string)$value)) === 1;
}

function is_valid_bid_amount($value, $minimum_price) {
  if (!is_money_value($value)) {
    return false;
  }

  $amount = filter_var(trim((string)$value), FILTER_VALIDATE_FLOAT);
  return $amount !== false && $amount >= (float)$minimum_price;
}

// display_time_remaining:
// Helper function to help figure out what time to display
function display_time_remaining($interval) {

    if ($interval->days == 0 && $interval->h == 0) {
      // Less than one hour remaining: print mins + seconds:
      $time_remaining = $interval->format('%im %Ss');
    }
    else if ($interval->days == 0) {
      // Less than one day remaining: print hrs + mins:
      $time_remaining = $interval->format('%hh %im');
    }
    else {
      // At least one day remaining: print days + hrs:
      $time_remaining = $interval->format('%ad %hh');
    }

  return $time_remaining;

}

// print_listing_li:
// This function prints an HTML <li> element containing an auction listing
function print_listing_li($item_id, $title, $desc, $price, $num_bids, $end_time)
{
    // Prevents modifying pages from DB entries 
  if (mb_strlen($desc) > 250) {
    $desc_shortened = mb_substr($desc, 0, 250) . '...';
  }
  else {
    $desc_shortened = $desc;
  }
  $desc_shortened = htmlspecialchars($desc_shortened);
  $title = htmlspecialchars($title);
  
  // Fix language of bid vs. bids
  if ($num_bids == 1) {
    $bid = ' bid';
  }
  else {
    $bid = ' bids';
  }
  
  // Calculate time to auction end
  $now = new DateTime();
  if ($now > $end_time) {
    $time_remaining = 'This auction has ended';
  }
  else {
    // Get interval:
    $time_to_end = date_diff($now, $end_time);
    $time_remaining = display_time_remaining($time_to_end) . ' remaining';
  }
  
  // Print HTML
  echo('
    <li class="list-group-item d-flex justify-content-between">
    <div class="p-2 mr-5"><h5><a href="listing.php?item_id=' . $item_id . '">' . $title . '</a></h5>' . $desc_shortened . '</div>
    <div class="text-center text-nowrap"><span style="font-size: 1.5em">£' . number_format($price, 2) . '</span><br/>' . $num_bids . $bid . '<br/>' . $time_remaining . '</div>
  </li>'
  );
}

